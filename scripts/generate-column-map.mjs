/**
 * Regenerates server/middleware/table-columns.js from the live PostgREST spec.
 *
 * Sibling of generate-coerce-list.mjs, which answers "is a blank string legal
 * for this column". This answers the other half: "is this a column at all".
 *
 * The rehearsal dinner needed it. That endpoint spread the whole request body
 * into an upsert, the form had picked up a userId field somewhere along the
 * way, and PostgREST refused every save from May onwards with an error about a
 * user id on a page about a rehearsal dinner. Four other endpoints write the
 * same way and are only safe because nothing has yet sent them a field that
 * does not exist.
 *
 * Writes the file. Run it after any migration that adds or drops columns, and
 * read the diff:
 *
 *   node scripts/generate-column-map.mjs
 */
import dotenv from 'dotenv';
import { writeFileSync, readFileSync, existsSync } from 'fs';
import { fileURLToPath } from 'url';
import path from 'path';

const here = path.dirname(fileURLToPath(import.meta.url));
const root = path.join(here, '..');
dotenv.config({ path: path.join(root, '.env') });

const url = process.env.VITE_SUPABASE_URL;
const key = process.env.SUPABASE_SERVICE_ROLE_KEY;
if (!url || !key) {
  console.error('VITE_SUPABASE_URL and SUPABASE_SERVICE_ROLE_KEY must be set');
  process.exit(1);
}

const res = await fetch(`${url}/rest/v1/`, {
  headers: { apikey: key, Authorization: `Bearer ${key}` },
});
if (!res.ok) {
  console.error(`Schema fetch failed: ${res.status} ${await res.text()}`);
  process.exit(1);
}
const spec = await res.json();
const definitions = spec.definitions || {};

const tables = Object.keys(definitions).sort();
if (!tables.length) {
  console.error('The schema spec came back with no tables. Not overwriting the file.');
  process.exit(1);
}

const entries = tables.map(t => {
  const cols = Object.keys(definitions[t].properties || {}).sort();
  return `  ${JSON.stringify(t)}: [${cols.map(c => JSON.stringify(c)).join(', ')}],`;
});

const out = `/**
 * Every column of every table, as PostgREST sees it.
 *
 * Generated by scripts/generate-column-map.mjs — do not hand-edit, regenerate
 * after a migration and read the diff.
 *
 * This exists because an endpoint that spreads a request body into a write
 * fails on the first field that is not a column, and fails in the vocabulary
 * of the database rather than of the person using it. Grace was told "could
 * not find user id" while saving a rehearsal dinner, because the form had
 * picked up a userId field and rehearsal_dinner has no such column. Every save
 * had failed that way since May and nothing said so.
 *
 * Use \`onlyColumns\` on anything that writes a caller-supplied object.
 */

export const TABLE_COLUMNS = {
${entries.join('\n')}
};

/**
 * The parts of \`body\` that are actually columns of \`table\`.
 *
 * Anything dropped is returned in \`ignored\` rather than swallowed, because a
 * dropped key is usually a client sending something harmless and occasionally
 * the field that was meant to save. Callers should log it.
 *
 * An unknown table returns the body untouched: a missing generated entry must
 * not quietly empty a write. Regenerate instead.
 */
export function onlyColumns(table, body) {
  const columns = TABLE_COLUMNS[table];
  if (!columns) return { fields: { ...body }, ignored: [], unknownTable: true };
  const fields = {};
  const ignored = [];
  for (const [k, v] of Object.entries(body || {})) {
    if (columns.includes(k)) fields[k] = v;
    else ignored.push(k);
  }
  return { fields, ignored, unknownTable: false };
}
`;

const target = path.join(root, 'server', 'middleware', 'table-columns.js');
const before = existsSync(target) ? readFileSync(target, 'utf8') : '';
writeFileSync(target, out);

console.log(`${tables.length} tables, ${tables.reduce((n, t) => n + Object.keys(definitions[t].properties || {}).length, 0)} columns`);
console.log(before === out ? 'No change.' : `Wrote server/middleware/table-columns.js${before ? ' (changed)' : ' (new)'}`);
